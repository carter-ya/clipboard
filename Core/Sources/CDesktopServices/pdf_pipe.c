#define _POSIX_C_SOURCE 200809L
#include "desktop_services.h"
#ifdef __linux__
#include <errno.h>
#include <pthread.h>
#include <signal.h>
#include <time.h>
#include <unistd.h>

/* A cancelled worker can close stdin during a blocked write. Block SIGPIPE
   only on this writer thread, consume only the signal generated by EPIPE,
   and restore its previous mask. Never change the application's signal policy. */
int cds_pdf_pipe_write(int descriptor, const unsigned char *bytes, size_t length) {
  if (descriptor < 0 || !bytes || length > 1024 * 1024) return -1;
  sigset_t pipe, previous, pending;
  sigemptyset(&pipe); sigaddset(&pipe, SIGPIPE);
  if (pthread_sigmask(SIG_BLOCK, &pipe, &previous) != 0) return -1;
  if (sigpending(&pending) != 0) { pthread_sigmask(SIG_SETMASK, &previous, NULL); return -1; }
  int already_pending = sigismember(&pending, SIGPIPE), broken = 0, result = 1;
  size_t position = 0;
  while (position < length) {
    ssize_t count = write(descriptor, bytes + position, length - position);
    if (count < 0 && errno == EINTR) continue;
    if (count <= 0) { broken = count < 0 && errno == EPIPE; result = -1; break; }
    position += (size_t)count;
  }
  if (broken && !already_pending) {
    struct timespec immediate = {0, 0};
    while (sigtimedwait(&pipe, NULL, &immediate) < 0 && errno == EINTR) {}
  }
  if (pthread_sigmask(SIG_SETMASK, &previous, NULL) != 0) result = -1;
  return result;
}
#else
int cds_pdf_pipe_write(int descriptor, const unsigned char *bytes, size_t length) {
  (void)descriptor; (void)bytes; (void)length; return -1;
}
#endif
